def get(lang: str, key: str) -> str:
    return MESSAGES.get(lang, MESSAGES[DEFAULT_LANGUAGE])[key]


def build_greeting(order: dict) -> str:
    lang = order["language"]
    product = order.get("product", "")
    if product and order.get("extra_items"):
        product = get(lang, "and_more").format(product=product, n=order["extra_items"])
    items = f"{product}, " if product else ""
    return get(lang, "greeting").format(
        store=config.STORE_NAME, items=items, total=order["total"], number=order["number"]
    )